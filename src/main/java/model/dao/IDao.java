package model.dao;

import java.util.List;

/**
 * Интерфейс доступа к данным (паттерн DAO, ЛР7).
 *
 * <p>Описывает базовые операции над DO-классами одной модели данных.
 * Дженерики позволяют писать один класс DAO для разных типов данных:
 * {@code T} - тип DO-класса, {@code ID} - тип ключа.</p>
 *
 * <p>Для хранилища определённого типа создаётся свой класс DAO, например
 * {@link SqlDao} для реляционного хранилища (SQLite) и {@link NoSqlDao} для
 * документного (MongoDB).</p>
 *
 * @param <T> тип DO-класса
 * @param <ID> тип ключа
 */
public interface IDao<T, ID> {

    /** Сохранить объект (создать или перезаписать). */
    void save(T entity);

    /** Найти объект по ключу или {@code null}, если его нет. */
    T findById(ID id);

    /** Все объекты хранилища. */
    List<T> findAll();

    /** Удалить объект по ключу. */
    void deleteById(ID id);
}

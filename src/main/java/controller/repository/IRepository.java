package controller.repository;

import java.util.List;

/**
 * Интерфейс репозитория бизнес-объекта (ЛР6, паттерн «Репозиторий»).
 *
 * <p>Репозиторий - это слой доступа к данным: он скрывает способ хранения
 * бизнес-объектов и преобразует их в DO-классы ({@code model.data}) и обратно.
 * Контроллер работает только с бизнес-объектами и не знает, как они хранятся.
 * Выдача идентификаторов - ответственность репозитория, поэтому метод
 * {@link #save(Object)} сам назначает идентификатор новому объекту.</p>
 *
 * @param <T> тип бизнес-объекта
 */
public interface IRepository<T> {

    /** Все бизнес-объекты из хранилища. */
    List<T> findAll();

    /** Бизнес-объект по идентификатору или {@code null}, если его нет. */
    T findById(Long id);

    /** Сохранить бизнес-объект (создать или перезаписать). */
    T save(T item);

    /** Удалить бизнес-объект. {@code false}, если его не было. */
    boolean delete(Long id);
}
